//! Performance harness for bergshamra-dsig enveloped signing and verification.
//!
//! This benchmark quantifies the "bridge win": the difference between the
//! string-oriented API (which parses XML text, signs, and reserializes) and the
//! document-native API (which mutates an already-parsed `uppsala::Document` in
//! place). Bindings such as pybergshamra call the document path to avoid a
//! serialize + reparse round trip on every sign/verify.
//!
//! Every sign and verify canonicalizes the whole document (an enveloped
//! signature with `URI=""`), so these numbers also capture the end-to-end
//! effect of bergshamra-c14n throughput at scale.
//!
//! Inputs are generated deterministically in-code (a synthetic SAML-metadata
//! aggregate) at two sizes, ~1 MB and ~20 MB, so the harness is reproducible and
//! self-contained.
//!
//! Run:    cargo bench -p bergshamra-dsig --bench dsig
//! Save:   cargo bench -p bergshamra-dsig --bench dsig -- --save-baseline before
//! Compare cargo bench -p bergshamra-dsig --bench dsig -- --baseline before

use bergshamra_core::algorithm;
use bergshamra_dsig::context::DsigContext;
use bergshamra_dsig::sign::{sign, sign_enveloped_document, EnvelopedSignatureOptions};
use bergshamra_dsig::verify::{verify, verify_document};
use bergshamra_keys::KeysManager;
use criterion::{black_box, criterion_group, criterion_main, BenchmarkId, Criterion, Throughput};
use uppsala::Document;

