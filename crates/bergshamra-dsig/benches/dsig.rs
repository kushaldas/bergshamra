/// The `<ds:Signature>` skeleton generated by [`sign_enveloped_document`] for a
/// whole-document (`URI=""`) enveloped RSA-SHA256 signature. Embedding it in the
/// string-path template makes both paths sign the identical structure.
const SIGNATURE_SKELETON: &str = concat!(
    "<ds:Signature xmlns:ds=\"http://www.w3.org/2000/09/xmldsig#\">",
    "<ds:SignedInfo>",
    "<ds:CanonicalizationMethod Algorithm=\"http://www.w3.org/2001/10/xml-exc-c14n#\"/>",
    "<ds:SignatureMethod Algorithm=\"http://www.w3.org/2001/04/xmldsig-more#rsa-sha256\"/>",
    "<ds:Reference URI=\"\">",
    "<ds:Transforms>",
    "<ds:Transform Algorithm=\"http://www.w3.org/2000/09/xmldsig#enveloped-signature\"/>",
    "<ds:Transform Algorithm=\"http://www.w3.org/2001/10/xml-exc-c14n#\"/>",
    "</ds:Transforms>",
    "<ds:DigestMethod Algorithm=\"http://www.w3.org/2001/04/xmlenc#sha256\"/>",
    "<ds:DigestValue></ds:DigestValue>",
    "</ds:Reference>",
    "</ds:SignedInfo>",
    "<ds:SignatureValue></ds:SignatureValue>",
    "<ds:KeyInfo><ds:X509Data/></ds:KeyInfo>",
    "</ds:Signature>",
);

/// Build a signing context backed by the embedded RSA-2048 key.
fn signing_context() -> DsigContext {
    let key = bergshamra_keys::loader::load_rsa_private_pem(RSA_2048_PEM.as_bytes())
        .expect("embedded RSA-2048 PEM must load");
    let mut keys = KeysManager::new();
    keys.add_key(key);
    DsigContext::new_permissive(keys)
}

/// Deterministically generate a SAML-metadata aggregate of roughly
/// `target_bytes`, returning `(plain, template)`:
///
/// - `plain` — the aggregate with no signature, parsed by the document path.
/// - `template` — the same aggregate with the whole-document signature skeleton
///   inserted as the root's first child, signed by the string path.
///
/// Both share identical body content so the two paths do equal signing work.
fn saml_aggregate(target_bytes: usize) -> (String, String) {
    // One namespace-rich EntityDescriptor entry, ~1.5 KB, escapable bytes
    // sprinkled through text and attribute values to exercise escape paths.
    let entry = |i: usize| -> String {
        format!(
            "<md:EntityDescriptor entityID=\"https://idp{i}.example.org/idp &amp; co\">\
<md:IDPSSODescriptor protocolSupportEnumeration=\"urn:oasis:names:tc:SAML:2.0:protocol\">\
<md:KeyDescriptor use=\"signing\">\
<ds:KeyInfo><ds:X509Data>\
<ds:X509Certificate>MIICertificateDataForEntity{i}Base64Padding0123456789abcdefghijklmnop\
qrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789+/abcdefghijklmnopqrstuvwxyz</ds:X509Certificate>\
</ds:X509Data></ds:KeyInfo>\
</md:KeyDescriptor>\
<md:SingleSignOnService Binding=\"urn:oasis:names:tc:SAML:2.0:bindings:HTTP-Redirect\" \
Location=\"https://idp{i}.example.org/sso?a=1&amp;b=2\"/>\
<md:SingleSignOnService Binding=\"urn:oasis:names:tc:SAML:2.0:bindings:HTTP-POST\" \
Location=\"https://idp{i}.example.org/sso/post\"/>\
</md:IDPSSODescriptor>\
<md:Organization>\
<md:OrganizationName xml:lang=\"en\">Example Org {i} &lt; &amp; &gt;</md:OrganizationName>\
<md:OrganizationDisplayName xml:lang=\"en\">Example Organization Number {i}</md:OrganizationDisplayName>\
<md:OrganizationURL xml:lang=\"en\">https://idp{i}.example.org/about</md:OrganizationURL>\
</md:Organization>\
</md:EntityDescriptor>"
        )
    };

    let open = "<md:EntitiesDescriptor xmlns:md=\"urn:oasis:names:tc:SAML:2.0:metadata\" \
xmlns:ds=\"http://www.w3.org/2000/09/xmldsig#\" Name=\"https://example.org/aggregate\">";
    let close = "</md:EntitiesDescriptor>";

    let mut body = String::with_capacity(target_bytes + 4096);
    let mut i = 0;
    while open.len() + body.len() + close.len() < target_bytes {
        body.push_str(&entry(i));
        i += 1;
    }

    let mut plain = String::with_capacity(open.len() + body.len() + close.len());
    plain.push_str(open);
    plain.push_str(&body);
    plain.push_str(close);

    let mut template =
        String::with_capacity(open.len() + SIGNATURE_SKELETON.len() + body.len() + close.len());
    template.push_str(open);
    template.push_str(SIGNATURE_SKELETON);
    template.push_str(&body);
    template.push_str(close);

    (plain, template)
}

/// Enveloped-signature options matching [`SIGNATURE_SKELETON`].
fn enveloped_options() -> EnvelopedSignatureOptions<'static> {
    EnvelopedSignatureOptions::new(
        None,
        algorithm::RSA_SHA256,
        algorithm::SHA256,
        algorithm::EXC_C14N,
        None,
    )
}

/// The two benchmark sizes: ~1 MB and ~20 MB.
fn sizes() -> [(&'static str, usize); 2] {
    [("1mb", 1 << 20), ("20mb", 20 << 20)]
}

fn bench_sign(c: &mut Criterion) {
    let ctx = signing_context();
    let mut group = c.benchmark_group("sign");
    group.sample_size(10);
    for (name, target) in sizes() {
        let (plain, template) = saml_aggregate(target);
        group.throughput(Throughput::Bytes(plain.len() as u64));

        // String path: parse the template, fill digests/signature, reserialize.
        group.bench_with_input(BenchmarkId::new("string", name), &template, |b, tmpl| {
            b.iter(|| {
                let signed = sign(&ctx, black_box(tmpl)).expect("string signing must succeed");
                black_box(signed);
            });
        });

        // Document path: build the Signature in place and sign the live DOM.
        // The document is mutated in place, so a fresh `Document<'static>` is
        // re-parsed per iteration in the (untimed) setup closure.
        group.bench_with_input(BenchmarkId::new("document", name), &plain, |b, plain| {
            b.iter_batched(
                || {
                    uppsala::parse(plain)
                        .expect("aggregate must parse")
                        .into_static()
                },
                |mut doc: Document<'static>| {
                    sign_enveloped_document(&ctx, &mut doc, enveloped_options())
                        .expect("document signing must succeed");
                    black_box(doc.to_xml());
                },
                criterion::BatchSize::SmallInput,
            );
        });
    }
    group.finish();
}

fn bench_verify(c: &mut Criterion) {
    let ctx = signing_context();
    let mut group = c.benchmark_group("verify");
    group.sample_size(10);
    for (name, target) in sizes() {
        let (plain, _template) = saml_aggregate(target);
        // Produce a real signed document once, outside the timed region.
        let mut doc = uppsala::parse(&plain)
            .expect("aggregate must parse")
            .into_static();
        sign_enveloped_document(&ctx, &mut doc, enveloped_options())
            .expect("signing the verify fixture must succeed");
        let signed_xml = doc.to_xml();
        // Confirm the fixture actually verifies before timing.
        assert!(
            verify(&ctx, &signed_xml)
                .expect("fixture verify must not error")
                .is_valid(),
            "verify fixture must be a valid signature"
        );

        group.throughput(Throughput::Bytes(signed_xml.len() as u64));

        // String path: reparse the signed XML, then verify.
        group.bench_with_input(BenchmarkId::new("string", name), &signed_xml, |b, xml| {
            b.iter(|| {
                let result = verify(&ctx, black_box(xml)).expect("string verify must not error");
                black_box(result);
            });
        });

        // Document path: verify against an already-parsed document (read-only).
        let parsed = uppsala::parse(&signed_xml)
            .expect("signed XML must parse")
            .into_static();
        group.bench_with_input(BenchmarkId::new("document", name), &parsed, |b, doc| {
            b.iter(|| {
                let result =
                    verify_document(&ctx, black_box(doc)).expect("document verify must not error");
                black_box(result);
            });
        });
    }
    group.finish();
}

criterion_group!(benches, bench_sign, bench_verify);
criterion_main!(benches);
